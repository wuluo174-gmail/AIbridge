let locale = $state<Locale>(
  (typeof localStorage !== 'undefined' && localStorage.getItem('bridge-locale') as Locale) || 'zh-CN'
)

export function getLocale(): Locale { return locale }
export function setLocale(l: Locale) { locale = l; localStorage.setItem('bridge-locale', l) }
export function t(key: string, params?: Record<string, string | number>): string {
  let msg = messages[locale]?.[key] ?? key
  if (params) {
    msg = msg.replace(/@\{(\w+)\}/g, (_, k) => {
      const ref = String(params[k] ?? k)
      return messages[locale]?.[ref] ?? ref
    })
    for (const [k, v] of Object.entries(params))
      msg = msg.replaceAll(`{${k}}`, String(v))
  }
  return msg
}
